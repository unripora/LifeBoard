package com.lifeboard.plugin.api

/**
 * 登录交互意图。
 *
 * ## 为什么要区分意图
 *
 * 现有协议里「首次进入登录」与「显式重新开始」都传空表单，插件无法区分。
 * 小米健康这类多轮认证流程会把空表单当作「重新开始」从而清空中间态，
 * 导致用户卡在验证码界面、无法回到账号密码。
 *
 * 新增可选 [LoginOptions.intent] 后，恢复、提交、重启、放弃各有明确语义。
 *
 * ## 兼容
 *
 * 旧调用（无 options）保持原有空表单语义，不触发任何清理。
 * 只有声明 `contract.loginIntent` 的插件使用新意图；新包在旧宿主缺 options 时
 * 使用明确的旧交互降级，不声称支持流程恢复。
 */
enum class LoginIntent {
    /** 打开登录入口：只读取并展示可恢复阶段，不提交、不清空 */
    OPEN,

    /** 提交当前输入：推进当前认证步骤 */
    SUBMIT,

    /** 重新开始：清理当前中间态，返回首轮（账号密码） */
    RESTART,

    /** 放弃：清理当前中间态并结束；其应答只确认清理，不映射为登录成功，不触发采集 */
    ABANDON
}

/**
 * 登录调用的可选参数。
 *
 * [intent] 缺省时不传意图，插件按旧协议处理（空表单语义）。
 */
data class LoginOptions(
    val intent: LoginIntent? = null,
)
